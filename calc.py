def scenarios():
    rows = []
    for (mode, origin), (fuel, vol), age, price in product(
            SCENARIO_MODES, SCENARIO_ENGINES, SCENARIO_AGES, SCENARIO_PRICES):
        c = Car(price, fuel, vol, age, mode, origin, доставка_eur=DELIVERY_EUR)
        rows.append({"маршрут": MODE_LABEL[(mode, origin)], **asdict(c), **calc(c)})
    return rows


def write_scenarios():
    import pandas as pd
    from paths import OUT
    df = pd.DataFrame(scenarios())
    df.to_csv(OUT / "сценарии.csv", index=False, encoding="utf-8-sig")
    print(len(df), "сценариев")
    return df



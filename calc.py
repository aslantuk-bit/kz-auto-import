"""Калькулятор платежей при ввозе легкового автомобиля (M1, 8703) в РК с постановкой на учёт.

Ставки на дату as_of из sources/raw/calc_params.json (её обновляет актуализация, actualize.py);
каждая константа помечена нормой. Сверка констант с базой ставок — в test_calc.py. Запуск без аргументов строит сетку сценариев out/сценарии.csv.

Режимы:
  ДТ          — ввоз из третьих стран по декларации на товары (юрлицо или физлицо);
                пошлина по ставкам РК по ВТО, если позиция есть в перечне, иначе по ЕТТ.
  ПТД         — физлицо из третьих стран, личное пользование: единая ставка (ЕТП) / СТП.
Доставка и страховка до границы ЕАЭС (доставка_eur) входят в таможенную стоимость по ДТ — в РК
или в стране растаможки (ТК ЕАЭС ст. 40); по ПТД база — цена покупки без перевозки (Кодекс РК
ст. 350). Для машин с рынка РФ/РБ доставка из третьих стран не учитывается.
  ЕАЭС_ЮЛ     — ввоз из ЕАЭС юрлицом/ИП: НДС и акциз через налоговую (ФНО 328.00).
  ЕАЭС_ФЛ     — ввоз из ЕАЭС физлицом не для бизнеса: косвенные налоги не взимаются.
Для ЕАЭС с происхождением «третьи» считается цепочка: машину из третьих стран растамаживают в
Кыргызстане (страна="КГ") или Армении («АМ») по ЕТТ с их НДС и сборами (ABROAD), затем ввозят в РК.
Для «РФ_РБ» цена — цена машины на рынке России или Беларуси, пошлина там уже в цене.
Происхождение для утильсбора: «третьи» (коэффициент 1, включая АМ и КГ) или «РФ_РБ» (коэффициент 2).
"""

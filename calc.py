@dataclass
class Car:
    стоимость_eur: float      # цена покупки (цена сделки), EUR
    тип: str                  # см. FUELS; гибрид_двс — мощнее ДВС, гибрид_эл — мощнее электромотор
    объём: int = 0            # см³, для электро 0
    возраст: int = 0          # полных лет с выпуска (для таможни: <3 — новый)
    режим: str = "ДТ"
    происхождение: str = "третьи"   # «третьи» или «РФ_РБ»
    возраст_рег: int | None = None  # для сбора за регистрацию: текущий год − год выпуска; None = возраст
    доставка_eur: float = 0.0       # доставка и страховка до границы ЕАЭС, EUR (только третьи страны)
    страна: str = "КГ"              # где растамаживают машину на маршрутах ЕАЭС из третьих стран

    @property
    def рег(self):
        return self.возраст if self.возраст_рег is None else self.возраст_рег

    @property
    def транзит(self):
        """Маршрут «третьи страны → растаможка в КГ/АМ → РК»."""
        return self.режим.startswith("ЕАЭС") and self.происхождение == "третьи"

    @property
    def доставка(self):
        """Доставка из третьих стран: у ДТ, ПТД и растаможки в КГ/АМ; у машин с рынка РФ/РБ её нет."""
        return self.доставка_eur if self.режим in ("ДТ", "ПТД") or self.транзит else 0.0

    @property
    def база_eur(self):
        """Таможенная стоимость: по ДТ и при растаможке в КГ/АМ — цена плюс доставка до границы ЕАЭС."""
        return self.стоимость_eur + (self.доставка if self.режим == "ДТ" or self.транзит else 0.0)


def _band(v, edges):
    """Индекс полосы по верхним границам включительно."""
    for i, e in enumerate(edges):
        if v <= e:
            return i
    return len(edges)


# ЕТТ ЕАЭС (Решение Совета ЕЭК № 80, гр. 87, ред. 22.01.2026)
ETT_PETROL_EDGES = (1000, 1500, 1800, 2300, 3000)
ETT_PETROL_MIN_3_7 = (0.36, 0.4, 0.36, 0.44, 0.44, 0.8)
ETT_PETROL_OVER7 = (1.4, 1.5, 1.6, 2.2, 2.2, 3.2)
ETT_DIESEL_EDGES = (1500, 2500)
ETT_DIESEL_MIN_3_7 = (0.32, 0.4, 0.8)
ETT_DIESEL_OVER7 = (1.5, 2.2, 3.2)

# Решение № 107, прил. 2, табл. 2, п. 3 — ЕТП для физлиц
PTD_NEW = ((8500, 0.54, 2.5), (16700, 0.48, 3.5), (42300, 0.48, 5.5),
           (84500, 0.48, 7.5), (169000, 0.48, 15), (float("inf"), 0.48, 20))
PTD_EDGES = (1000, 1500, 1800, 2300, 3000)
PTD_3_5 = (1.5, 1.7, 2.5, 2.7, 3.0, 3.6)
PTD_OVER5 = (3.0, 3.2, 3.5, 4.8, 5.0, 5.7)

# Утильсбор: приказ МЭПР № 54 от 20.03.2026, прил. 4 (50 МРП × коэффициент)
UTIL_EDGES = (1000, 2000, 3000)
UTIL_K1 = (1.5, 3.5, 5, 11.5)
UTIL_K2 = (22, 136, 164, 246)
UTIL_EV = {"третьи": 0, "РФ_РБ": 60}


def duty_ett(c: Car):
    v_kzt = c.база_eur * EUR
    if c.тип in ("гибрид_эл", "электро"):
        return 0.15 * v_kzt
    ice = "дизель" if c.тип == "дизель" else "бензин"
    if c.возраст < 3:
        if ice == "бензин" and c.объём > 2800:
            return 0.125 * v_kzt
        return 0.15 * v_kzt
    if ice == "бензин":
        b = _band(c.объём, ETT_PETROL_EDGES)
        mn, over7 = ETT_PETROL_MIN_3_7[b], ETT_PETROL_OVER7[b]
    else:
        b = _band(c.объём, ETT_DIESEL_EDGES)
        mn, over7 = ETT_DIESEL_MIN_3_7[b], ETT_DIESEL_OVER7[b]
    if c.возраст <= 7:
        return max(0.20 * v_kzt, mn * c.объём * EUR)
    return over7 * c.объём * EUR


def duty_wto(c: Car):
    """Ставки РК по ВТО (Решение № 59). None — позиции нет в перечне, применяется ЕТТ."""
    v_kzt = c.база_eur * EUR
    if c.тип in ("гибрид_эл", "электро"):
        return 0.0
    if c.возраст < 3:
        return None
    if c.возраст <= 7:
        return 0.15 * v_kzt
    if c.тип in ("бензин", "гибрид_двс") and 1500 < c.объём <= 3000:
        return min(max(0.5 * c.объём * EUR, 0.15 * v_kzt), 0.18 * v_kzt)
    return max(0.15 * v_kzt, 0.6 * c.объём * EUR)


def etp(c: Car):
    """Единая ставка для физлица по ПТД (заменяет пошлину, НДС и акциз 100 тг/см³)."""
    if c.тип == "электро":
        duty = 0.15 * c.стоимость_eur * EUR          # СТП: пошлина по ЕТТ + НДС
        return duty + VAT * (c.стоимость_eur * EUR + duty)
    if c.возраст < 3:
        for limit, pct, mn in PTD_NEW:
            if c.стоимость_eur <= limit:
                return max(pct * c.стоимость_eur, mn * c.объём) * EUR
    b = _band(c.объём, PTD_EDGES)
    rate = PTD_3_5[b] if c.возраст <= 5 else PTD_OVER5[b]
    return rate * c.объём * EUR


def abroad(c: Car):
    """Платежи в стране растаможки (КГ/АМ): пошлина по ЕТТ, НДС, сборы и экологический налог, тг.

    НДС той страны остаётся в цене только у физлица: юрлицу РК продавец отгружает по 0%
    и возвращает свой НДС, а в РК платится НДС 16% (Договор о ЕАЭС, прил. 18, п. 3–4).
    """
    a = ABROAD[c.страна]
    base = c.база_eur * EUR
    duty = duty_ett(c)
    ev_free = c.тип == "электро" and a["НДС_электро_до"] is not None and c.возраст < a["НДС_электро_до"]
    vat = 0.0 if (ev_free or c.режим == "ЕАЭС_ЮЛ") else a["НДС"] * (base + duty)
    eco = next((r for top, r in a["эко"] if c.возраст <= top), 0.0) * base
    return {"пошлина_там": duty, "НДС_там": vat, "сборы_там": a["сбор"] * base + eco}


def util(c: Car):
    k = UTIL_K1 if c.происхождение == "третьи" else UTIL_K2
    if c.тип == "электро":
        return 50 * MRP * UTIL_EV[c.происхождение]
    return 50 * MRP * k[_band(c.объём, UTIL_EDGES)]


def reg_fee(c: Car):
    """НК ст. 615 п. 3, строки 4.1–4.2; возраст «включая год выпуска», происхождение не влияет."""
    ev = c.тип == "электро"
    if c.рег < 2:
        return 0.25 * MRP
    if c.рег < 3:
        return (25 if ev else 50) * MRP
    return (250 if ev else 500) * MRP


def transport_tax(c: Car):
    """НК ст. 565, легковые; коэффициент возраста применён ко всей сумме (трактовка спорна)."""
    if c.тип == "электро":
        return 0.0   # спорно: разъяснений по НК-2026 нет
    steps = ((1100, 1, None), (1500, 2, None), (2000, 3, 1500), (2500, 6, 2000),
             (3000, 9, 2500), (4000, 15, 3000), (float("inf"), 117, 4000))
    for top, mrp, base in steps:
        if c.объём <= top:
            tax = mrp * MRP + (7 * (c.объём - base) if base else 0)
            break
    if c.рег > 20:
        tax *= 0.5
    elif c.рег > 10:
        tax *= 0.7
    return tax


def calc(c: Car) -> dict:
    v_kzt = c.стоимость_eur * EUR      # цена машины — знаменатель доли платежей
    base = c.база_eur * EUR            # таможенная стоимость — база пошлины, НДС и акциза 10%
    r = {"пошлина": 0.0, "ставка_пошлины": "—", "ЕТП_СТП": 0.0, "таможенный_сбор": 0.0,
         "акциз_объём": 0.0, "акциз_10pct": 0.0, "НДС": 0.0,
         "пошлина_там": 0.0, "НДС_там": 0.0, "сборы_там": 0.0}
    if c.транзит:
        r.update(abroad(c))
        r["ставка_пошлины"] = f"ЕТТ в стране растаможки ({ABROAD[c.страна]['название']})"
        # цена покупки у продавца в КГ/АМ: таможенная стоимость, пошлина и сборы там
        base = base + r["пошлина_там"] + r["сборы_там"]
    ice_over3000 = c.тип != "электро" and c.объём > 3000
    excise_cc = 100 * c.объём if ice_over3000 else 0.0          # НК ст. 537, строка 21
    lux = max(0.10 * base - excise_cc, 0) if base >= LUX_THRESHOLD else 0.0  # строка 24, ст. 548 п. 10

    if c.режим == "ДТ":
        ett, wto = duty_ett(c), duty_wto(c)
        if wto is not None and wto <= ett:
            r["пошлина"], r["ставка_пошлины"] = wto, "ВТО (Решение № 59)"
        else:
            r["пошлина"], r["ставка_пошлины"] = ett, "ЕТТ (Решение № 80)"
        r["таможенный_сбор"] = CUSTOMS_FEE_MRP * MRP
        r["акциз_объём"], r["акциз_10pct"] = excise_cc, lux
        r["НДС"] = VAT * (base + r["пошлина"] + excise_cc + lux)
    elif c.режим == "ПТД":
        r["ЕТП_СТП"] = etp(c)
        r["ставка_пошлины"] = "СТП (ЕТТ + НДС)" if c.тип == "электро" else "ЕТП (Решение № 107)"
        r["акциз_10pct"] = lux   # спорно для ПТД: НК называет физлиц плательщиками
    elif c.режим == "ЕАЭС_ЮЛ":
        buy = base if c.транзит else v_kzt
        r["акциз_объём"], r["акциз_10pct"] = excise_cc, lux
        r["НДС"] = VAT * (buy + excise_cc + lux)
    elif c.режим == "ЕАЭС_ФЛ":
        r["акциз_10pct"] = lux
    else:
        raise ValueError(c.режим)

    r["утильсбор"] = util(c)
    r["сбор_первичная_регистрация"] = reg_fee(c)
    r["СРТС_и_номера"] = (1.25 + 2.8) * MRP
    r["за_рубежом"] = r["пошлина_там"] + r["НДС_там"] + r["сборы_там"]
    gov = ("пошлина", "ЕТП_СТП", "таможенный_сбор", "акциз_объём", "акциз_10pct", "НДС", "за_рубежом",
           "утильсбор", "сбор_первичная_регистрация", "СРТС_и_номера")
    r["итого_обязательные"] = sum(r[k] for k in gov)
    market = MARKET["ОГПО_год"] + (MARKET["брокер"] + MARKET["СВХ"] if c.режим in ("ДТ", "ПТД") else 0)
    if c.режим in ("ПТД", "ДТ"):
        market += MARKET["СБКТС"] + (MARKET["ЭПТС"] if c.режим == "ПТД" else 0)
    if c.транзит:   # СБКТС и ЭПТС оформляют в стране выпуска (ТР ТС 018/2011) — та же рыночная оценка
        market += (ABROAD[c.страна]["посредник_eur"] * EUR + ABROAD[c.страна]["перегон_кзт"]
                   + MARKET["СБКТС"] + MARKET["ЭПТС"])
    r["рыночные_оценка"] = market
    r["доставка_кзт"] = c.доставка * EUR
    r["итого_с_рыночными"] = r["итого_обязательные"] + market + r["доставка_кзт"]
    r["стоимость_кзт"] = v_kzt
    r["таможенная_стоимость_кзт"] = (c.база_eur * EUR if c.режим == "ДТ" or c.транзит
                                     else v_kzt if c.режим == "ПТД" else 0.0)
    r["доля_обязательных_pct"] = 100 * r["итого_обязательные"] / v_kzt
    r["налог_на_транспорт_год"] = transport_tax(c)
    flags = []
    if c.режим == "ПТД" and c.возраст > 5:
        flags.append("ЭПТС по ПТД только до 5 лет (приказ МПС № 474, с 26.09.2026, по СМИ) — регистрация невозможна")
    if r["ставка_пошлины"].startswith("ВТО"):
        flags.append("условный выпуск: обращение только в РК")
    if c.транзит:
        name = ABROAD[c.страна]["название"]
        flags.append(f"регистрация в РК не подтверждена: ЭПТС выдаёт {name}, обмена данными ЭПТС с РК нет "
                     "(Правила ЭПТС, п. 5-1; МПС РК), СБКТС физлицу на ввоз из ЕАЭС не выдают")
        if c.страна == "АМ":
            flags.append("путь из Армении — транзитом через Россию: риск утильсбора по коэффициенту 2")
        if c.режим == "ЕАЭС_ФЛ":
            flags.append("НДС 16% в РК не начислен (ввоз не для бизнеса, НК ст. 514 п. 6); спорно для машины "
                         "дороже 360 МРП (Критерии № 690)")
        if c.тип == "электро":
            flags.append(f"электромобиль, ввезённый в {name} по льготе ЕАЭС, нельзя передавать резидентам РК "
                         "(Решение Совета ЕЭК № 111); расчёт — для растаможки по ЕТТ")
    if c.режим == "ПТД" and lux:
        flags.append("акциз 10% при ПТД — спорно")
    r["примечания"] = "; ".join(flags)
    # округление «половина вверх» — как Math.round в calc.js
    return {k: (math.floor(v + 0.5) if isinstance(v, float) else v) for k, v in r.items()}



"""«Как сэкономить»: правила выбора машины и маршрута по полной сетке вариантов."""
import pandas as pd
import streamlit as st

import savings
from ui.common import money


def _m(v):
    return money(v, "млн") + " тг"


@st.cache_data
def _data():
    return savings.compute()


def render():
    d = _data()
    st.title("Как сэкономить")
    st.markdown(
        "**Самый выгодный профиль:** электромобиль или машина с ДВС до 2 000 см³, не старше 2 лет по году выпуска, "
        f"дешевле {money(d['lux']['eur'] // 100 * 100)} €, ввоз из Китая, Кореи или Японии по ДТ. "
        "Для дорогой машины 3–5 лет — ПТД.")
    st.caption(f"Посчитано калькулятором по {money(d['configs'])} машинам × 6 маршрутов: 9 двигателей, возраст 0–15 лет, "
               "12 цен от 5 до 150 тыс. €. Варианты, которые нельзя поставить на учёт, исключены. "
               "Сравниваются обязательные платежи; рыночные расходы одинаковы по смыслу и не меняют выбор.")

    st.header("Не ввозить через Россию и Беларусь")
    st.markdown(f"В лучшем случае дороже лучшего маршрута на **{_m(d['ru']['min'])}**, в среднем — на "
                f"**{_m(d['ru']['median'])}**. Причина — утильсбор по коэффициенту 2 (приказ МЭПР № 54).")

    st.header("Электромобиль — из третьих стран по ДТ")
    ev = d["ev"]["example"]
    st.markdown(f"Выигрывает в {d['ev']['wins']} из {d['ev']['n']} вариантов: пошлина 0% по перечню ВТО, утильсбора нет, "
                "остаются НДС 16% и сборы. Так же оформляется гибрид, у которого мощнее электромотор.")
    c = st.columns(3)
    c[0].metric("Электромобиль", _m(ev["электро"]))
    c[1].metric("Гибрид (мощнее электромотор)", _m(ev["гибрид_эл"]))
    c[2].metric("Бензин 2,0 л", _m(ev["бензин"]))
    st.caption(f"Машина за {money(d['ev']['example_price'])} €, 1 год, третьи страны · ДТ.")

    st.header("Возраст: граница — 3 года по году выпуска")
    a = d["age"]
    c = st.columns(3)
    c[0].metric("2 года вместо 1", "+" + _m(a["dt_1_2"]), help="Сбор за регистрацию 50 МРП вместо 0,25")
    c[1].metric("3 года вместо 2", "+" + _m(a["dt_2_3"]), help="Сбор за регистрацию 500 МРП вместо 50")
    c[2].metric("ПТД: 6 лет вместо 5", "+" + _m(a["ptd_5_6"]), help="Единая ставка старше 5 лет выше; ЭПТС не оформят")
    st.markdown("Сбор за регистрацию считает возраст «включая год выпуска»: машина декабря 2023 года в 2026-м — уже "
                "«3 года и старше», января 2024-го — ещё нет. Разница до 2 млн тг может решаться месяцем выпуска.")
    st.caption(f"Бензин 2,0 л, {money(a['price'])} €, третьи страны · ДТ.")

    st.header("Объём: до 3 000 см³, лучше до 2 000")
    v = d["volume"]
    st.dataframe(pd.DataFrame([
        {"Граница": "2 000 → 2 100 см³", "Что меняется": "утильсбор 3,5 → 5", "Цена перехода": "+" + _m(v["v2000_2100"])},
        {"Граница": "3 000 → 3 100 см³", "Что меняется": "акциз 100 тг за каждый см³ всего объёма, утильсбор 11,5",
         "Цена перехода": "+" + _m(v["v3000_3100"])},
    ]), hide_index=True, use_container_width=True)
    st.markdown(f"Парадокс ЕТТ: новая бензиновая машина 2,8–3,0 л платит пошлину 12,5% вместо 15%, поэтому новая 2,9 л "
                f"({money(v['new_2900'])} тг) дешевле новой 2,0 л ({money(v['new_2000'])} тг) той же цены.")
    st.caption(f"Машина за {money(v['price'])} €; переходы — для 4 лет, сравнение 2,9 и 2,0 л — для 1 года.")

    st.header("ПТД или ДТ для физлица")
    t = d["ptd_dt"]
    age_word = {0: "лет", 1: "год", 5: "лет"}
    df = pd.DataFrame([[f"{x / 1e6:+.1f}".replace(".", ",") for x in t["rows"][str(age)]] for age in range(6)],
                      index=[f"{age} {age_word.get(age, 'года')}" for age in range(6)],
                      columns=[f"{money(p)} €" for p in t["prices"]])
    st.dataframe(df, use_container_width=True)
    st.markdown("ПТД минус ДТ, млн тг, бензин 2,0 л: минус — ПТД дешевле. Новые машины выгоднее по ДТ всегда; "
                "для б/у 3–5 лет единая ставка считается от объёма, а не от цены, поэтому с 20 тыс. € ПТД "
                "выигрывает всё сильнее. Старше 5 лет — только ДТ: ЭПТС по ПТД не оформят. Минус ДТ — "
                "условный выпуск: машина обращается только в РК.")

    st.header("Кыргызстан и Армения: дёшево на бумаге")
    sh_kz, sh_l = d["eaeu"]["by_kz"], d["eaeu"]["by_landed"]
    st.markdown(f"По платежам в РК физлицо из Кыргызстана или Армении выигрывает в **{sh_kz.get('kg_fl', 0):.0f}%** "
                f"вариантов: пошлины нет, НДС с физлица не берут. Если прибавить пошлину ЕТТ, уже заложенную в цену "
                f"машины там, — в **{sh_l.get('kg_fl', 0):.0f}%**. Это оценка сверху: местный НДС, сборы и маржа "
                "перепродавца не учтены.")
    st.markdown("Правило: маршрут выгоден, только если машина на рынке Кыргызстана или Армении стоит не дороже той же "
                "машины в Китае или Корее плюс 15–20%. Регулярный ввоз могут признать предпринимательским — тогда "
                "НДС 16%. Электромобили, ввезённые туда по льготе ЕАЭС, резидентам РК передавать нельзя.")

    st.header("Цена и статус ввозящего")
    st.markdown(f"- Держаться ниже **{money(d['lux']['eur'] // 100 * 100)} €** ({_m(d['lux']['kzt'])}): с этого порога акциз 10%.\n"
                f"- У машины за {money(d['cheap']['price'])} € фиксированные платежи составляют "
                f"{d['cheap']['share_min']:.0f}–{d['cheap']['share_max']:.0f}% её стоимости.\n"
                "- Юрлицо — плательщик НДС берёт ввозной НДС в зачёт, поэтому для бизнеса ДТ реально дешевле, "
                "чем в расчётах: модель зачёт не учитывает.")

# ---------- форматирование ----------
def _num(x, digits=0):
    s = f"{x:,.{digits}f}".replace(",", " ")
    return s.replace(".", ",")


def tg(x):
    return _num(round(x)) + " тг"


def mln(x, signed=False, unit=True):
    s = _num(abs(x) / 1e6, 1) + (" млн тг" if unit else "")
    return ("−" if x < 0 else "+" if signed and x > 0 else "") + s


def eur(x):
    return _num(round(x)) + " €"


def pct(x):
    return _num(x) + "%"


# ---------- расчёт ----------
def car(price, fuel, cc, age, mode="ДТ", origin="третьи", **kw):
    return calc.calc(Car(price, fuel, cc, age, mode, origin, доставка_eur=kw.pop("delivery", D), **kw))


def total(price, fuel, cc, age, mode="ДТ", origin="третьи", **kw):
    return car(price, fuel, cc, age, mode, origin, **kw)["итого_обязательные"]


def _grid():
    rows = []
    for (fuel, cc), age, price in product(ENGINES, AGES, PRICES):
        for mode, origin, rid in ROUTES:
            c = Car(price, fuel, cc, age, mode, origin, доставка_eur=D)
            r = calc.calc(c)
            rows.append({
                "key": (fuel, cc, age, price), "fuel": fuel, "route": rid,
                "blocked": any(b in r["примечания"] for b in BLOCKS),
                "kz": r["итого_обязательные"],
                # плюс сама доставка до границы ЕАЭС и рыночные расходы (брокер, посредник в КР)
                "landed": price * EUR + r["итого_с_рыночными"],
            })
    return rows


def _winners(rows, col):
    best = {}
    for r in rows:
        if r["blocked"] or r["route"].startswith("ru"):
            continue
        b = best.get(r["key"])
        if b is None or r[col] < b[col]:
            best[r["key"]] = r
    return best


def _shares(best):
    n = len(best)
    out = {}
    for r in best.values():
        out[r["route"]] = out.get(r["route"], 0) + 1
    return {k: round(100 * v / n, 1) for k, v in sorted(out.items(), key=lambda kv: -kv[1])}


def _breakeven_delivery(price, fuel, cc, age):
    """Доставка, при которой ДТ сравнивается с ПТД (ПТД от доставки не зависит). None — ДТ дешевле всегда."""
    ptd = total(price, fuel, cc, age, "ПТД")
    if total(price, fuel, cc, age, "ДТ", delivery=0) >= ptd:
        return 0
    lo, hi = 0.0, 200000.0
    if total(price, fuel, cc, age, "ДТ", delivery=hi) < ptd:
        return None
    for _ in range(50):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if total(price, fuel, cc, age, "ДТ", delivery=mid) < ptd else (lo, mid)
    return lo


def compute():
    rows = _grid()
    by_kz, by_landed = _winners(rows, "kz"), _winners(rows, "landed")
    ru = sorted(r["kz"] - by_kz[r["key"]]["kz"] for r in rows if r["route"] == "ru_fl")
    ev = [w for k, w in by_landed.items() if k[0] == "электро"]

    p, a = 15000, 1
    ptd_dt = {age: {pr: total(pr, "бензин", 2000, age, "ПТД") - total(pr, "бензин", 2000, age, "ДТ") for pr in PRICES}
              for age in range(0, 6)}
    d = {
        "delivery_eur": D,
        "configs": len(by_kz),
        "routes_total": len(rows),
        "ru": {"min": ru[0], "median": ru[len(ru) // 2]},
        "ev": {"wins": sum(w["route"] == "dt" for w in ev), "n": len(ev),
               "example_price": 30000,
               "example": {"электро": total(30000, "электро", 0, a), "гибрид_эл": total(30000, "гибрид_эл", 1500, a),
                           "бензин": total(30000, "бензин", 2000, a)}},
        "age": {"price": p,
                "dt_1_2": total(p, "бензин", 2000, 2) - total(p, "бензин", 2000, 1),
                "dt_2_3": total(p, "бензин", 2000, 3) - total(p, "бензин", 2000, 2),
                "ptd_5_6": total(p, "бензин", 2000, 6, "ПТД") - total(p, "бензин", 2000, 5, "ПТД")},
        "volume": {"price": 25000,
                   "v2000_2100": total(25000, "бензин", 2100, 4) - total(25000, "бензин", 2000, 4),
                   "v3000_3100": total(25000, "бензин", 3100, 4) - total(25000, "бензин", 3000, 4),
                   "new_2900": total(25000, "бензин", 2900, 1), "new_2000": total(25000, "бензин", 2000, 1)},
        "ptd_dt": {"prices": list(PRICES), "rows": {str(k): [v[pr] for pr in PRICES] for k, v in ptd_dt.items()},
                   # с какой цены б/у 3–5 лет по ПТД дешевле, чем по ДТ
                   "from_price": min((pr for pr in PRICES if ptd_dt[4][pr] < 0), default=None)},
        "eaeu": {"by_kz": _shares(by_kz), "by_landed": _shares(by_landed)},
        "kg_if_open": _kg_if_open(rows),
        "lux": {"kzt": calc.LUX_THRESHOLD, "eur": calc.LUX_THRESHOLD / EUR},
        "cheap": {"price": 8000,
                  "share_min": min(100 * total(8000, f, c, 4, m) / (8000 * EUR)
                                   for f, c in (("бензин", 1500), ("бензин", 2000)) for m in ("ДТ",)),
                  "share_max": max(100 * total(8000, "бензин", 2000, ag, m) / (8000 * EUR)
                                   for ag in (1, 4) for m in ("ДТ", "ПТД"))},
    }
    d["sections"] = sections(d)
    d["footer"] = (f"Все суммы посчитаны калькулятором по ставкам, сверенным {calc.AS_OF:%d.%m.%Y}: "
                   f"МРП {_num(MRP)} тг, EUR {_num(EUR, 2)} тг на {calc.FX_DATE:%d.%m.%Y}. Машины из третьих стран — с доставкой {eur(D)} до границы ЕАЭС, "
                   "если не сказано иное. Расчёт справочный, не заменяет декларацию и разъяснения госорганов.")
    return d


# ---------- разделы ----------
def P(text):
    return {"t": "p", "text": text}


def L(*items):
    return {"t": "list", "items": list(items)}


def S(*items):
    return {"t": "steps", "items": [{"title": a, "text": b} for a, b in items]}


def TBL(head, rows, num=(), caption=None):
    b = {"t": "table", "head": list(head), "rows": [list(r) for r in rows], "num": list(num)}
    if caption:
        b["caption"] = caption
    return b


def FIG(*items):
    return {"t": "figures", "items": [list(x) for x in items]}


def NOTE(text):
    return {"t": "note", "text": text}


def WARN(text):
    return {"t": "warn", "text": text}


def sec(id_, title, *blocks):
    return {"id": id_, "title": title, "blocks": list(blocks)}



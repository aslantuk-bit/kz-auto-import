def _kg_if_open(rows):
    """Если бы регистрация работала: где физлицо через КР дешевле лучшего прямого маршрута (с посредником)."""
    best, kg = {}, {}
    for r in rows:
        if r["route"] == "kg_fl":
            kg[r["key"]] = r["landed"]
        elif r["route"] in ("dt", "ptd") and not r["blocked"]:
            best[r["key"]] = min(best.get(r["key"], float("inf")), r["landed"])
    gains = sorted(best[k] - kg[k] for k in kg if kg[k] < best[k])
    new_ice = [best[k] - kg[k] for k in kg if k[2] < 3 and k[0] in ("бензин", "дизель")]
    return {"share": round(100 * len(gains) / len(kg), 1), "median": gains[len(gains) // 2] if gains else 0,
            "new_ice_share": round(100 * sum(x > 0 for x in new_ice) / len(new_ice), 1),
            "new_ice_max": max(new_ice)}


def _route_cmp(price, fuel, cc, age):
    dt = car(price, fuel, cc, age, "ДТ")
    kg = car(price, fuel, cc, age, "ЕАЭС_ФЛ", страна="КГ")
    am = car(price, fuel, cc, age, "ЕАЭС_ФЛ", страна="АМ")
    full = lambda r: r["итого_с_рыночными"] - r["доставка_кзт"]  # noqa: E731  (доставка одинакова)
    return dt, kg, am, full(kg) - full(dt), full(am) - full(dt)


